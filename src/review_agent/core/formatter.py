"""
core/formatter.py — turn a list of Findings into a GitHub PR review.

Outputs two things:
  1. A top-level review body (Markdown summary posted as the PR review text).
  2. A list of inline comment dicts (one per finding that has a line number).

Both are plain Python — no GitHub or LangGraph dependencies here.
"""

from __future__ import annotations

from review_agent.core.passes import Finding, Severity

# Emoji prefix per severity — gives reviewers instant visual priority.
_SEVERITY_EMOJI: dict[Severity, str] = {
    "critical": "🔴",
    "high":     "🟠",
    "medium":   "🟡",
    "low":      "🔵",
    "info":     "⚪",
}

_SEVERITY_ORDER: list[Severity] = ["critical", "high", "medium", "low", "info"]


def _sort_key(f: Finding) -> int:
    try:
        return _SEVERITY_ORDER.index(f.severity)
    except ValueError:
        return len(_SEVERITY_ORDER)


def format_review(
    findings: list[Finding],
    pr_title: str,
    pr_author: str,
) -> tuple[str, list[dict]]:
    """
    Convert findings into (review_body, inline_comments).

    review_body    — Markdown string for the top-level PR review.
    inline_comments — list of {"path": str, "line": int, "body": str}
                      for findings with a known line number.
    """
    findings = sorted(findings, key=_sort_key)

    counts: dict[Severity, int] = {s: 0 for s in _SEVERITY_ORDER}
    for f in findings:
        if f.severity in counts:
            counts[f.severity] += 1

    # ── Build summary header ──────────────────────────────────────────────────
    lines: list[str] = [
        f"## 🤖 Automated Code Review — *{pr_title}*",
        "",
        (
            f"Hi @{pr_author}! Here's what the agent found across three passes "
            f"(security → correctness → design)."
        ),
        "",
        "### Summary",
        "",
    ]

    if not findings:
        lines.append("✅ No issues found. Looks good!")
    else:
        for sev in _SEVERITY_ORDER:
            n = counts[sev]
            if n:
                lines.append(f"- {_SEVERITY_EMOJI[sev]} **{sev.capitalize()}**: {n}")
        lines.append("")
        lines.append("> Inline comments below point to specific lines.")

    # ── Per-finding detail table ──────────────────────────────────────────────
    if findings:
        lines += [
            "",
            "### Findings",
            "",
            "| # | Sev | Pass | File | Line | Issue |",
            "|---|-----|------|------|------|-------|",
        ]
        for i, f in enumerate(findings, start=1):
            emoji = _SEVERITY_EMOJI.get(f.severity, "")
            line_str = str(f.line) if f.line else "—"
            issue_short = f.issue[:70] + "…" if len(f.issue) > 70 else f.issue
            lines.append(
                f"| {i} | {emoji} {f.severity} | {f.pass_name} "
                f"| `{f.file}` | {line_str} | {issue_short} |"
            )

    # ── Footer ────────────────────────────────────────────────────────────────
    lines += [
        "",
        "---",
        (
            "*Generated by [code-review-agent](https://github.com/Vinoth-Suryanarayanan/code-review-agent). "
            "This review is a starting point — human judgment is always final.*"
        ),
    ]

    review_body = "\n".join(lines)

    # ── Inline comments ───────────────────────────────────────────────────────
    inline_comments: list[dict] = []
    for f in findings:
        if f.line is None:
            continue
        emoji = _SEVERITY_EMOJI.get(f.severity, "")
        comment_body = (
            f"{emoji} **{f.severity.upper()} ({f.pass_name})**\n\n"
            f"**Issue:** {f.issue}\n\n"
            f"**Suggestion:** {f.suggestion}\n\n"
            f"*Source: {f.source}*"
        )
        inline_comments.append({
            "path": f.file,
            "line": f.line,
            "body": comment_body,
        })

    return review_body, inline_comments
